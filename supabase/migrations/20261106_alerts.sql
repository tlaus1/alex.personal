-- Alerts pushed into the dashboard by outside agents (e.g. Tomo AI).
--
-- Inserts happen ONLY through the `alert` edge function, which authenticates
-- the sender with its own ingest token and writes with the service role. There
-- is deliberately no INSERT policy: the browser can read and tidy alerts, but
-- nothing holding the publishable key or a user session can create them.

create table if not exists public.alerts (
  id          bigint generated by default as identity primary key,
  title       text        not null check (char_length(title) between 1 and 140),
  body        text                 check (char_length(body) <= 2000),
  level       text        not null default 'info' check (level in ('info','warn','urgent')),
  source      text        not null default 'tomo' check (char_length(source) <= 40),
  url         text                 check (url is null or (url like 'https://%' and char_length(url) <= 500)),
  read        boolean     not null default false,
  created_at  timestamptz not null default now()
);

create index if not exists alerts_created_idx on public.alerts (created_at desc);
create index if not exists alerts_unread_idx  on public.alerts (read) where not read;

alter table public.alerts enable row level security;

drop policy if exists "alerts read"   on public.alerts;
drop policy if exists "alerts update" on public.alerts;
drop policy if exists "alerts delete" on public.alerts;

create policy "alerts read"   on public.alerts for select to authenticated using (true);
create policy "alerts update" on public.alerts for update to authenticated using (true) with check (true);
create policy "alerts delete" on public.alerts for delete to authenticated using (true);

-- Readers may only flip `read`; they cannot rewrite what the agent said.
revoke update on public.alerts from authenticated;
grant  update (read) on public.alerts to authenticated;
grant  select, delete on public.alerts to authenticated;
revoke all on public.alerts from anon;
